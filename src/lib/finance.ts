/** Opens a clean, branded print window for a document node. */
export const printDocument = (elementId: string, documentTitle: string) => {
  const node = document.getElementById(elementId);
  if (!node) return;
  const win = window.open("", "_blank", "width=900,height=1000");
  if (!win) return;
  win.document.write(`<!doctype html><html><head><title>${documentTitle}</title>
    <style>
      *{box-sizing:border-box;}
      body{font-family:'Plus Jakarta Sans',system-ui,-apple-system,sans-serif;color:#0f172a;margin:32px;}
      .doc-head{text-align:center;border-bottom:3px double #0f2d5c;padding-bottom:12px;margin-bottom:20px;}
      .doc-head h1{margin:0;font-size:20px;color:#0f2d5c;letter-spacing:.02em;}
      .doc-head p{margin:2px 0;font-size:11px;color:#475569;}
      table{width:100%;border-collapse:collapse;margin-top:12px;font-size:13px;}
      th,td{padding:8px 10px;border-bottom:1px solid #e2e8f0;text-align:left;}
      th{background:#f1f5f9;font-size:11px;text-transform:uppercase;letter-spacing:.05em;color:#475569;}
      td.num,th.num{text-align:right;}
      .totals td{font-weight:700;}
      .meta{display:flex;justify-content:space-between;font-size:12px;gap:24px;flex-wrap:wrap;}
      .meta div{line-height:1.7;}
      .stamp{margin-top:28px;font-size:11px;color:#475569;display:flex;justify-content:space-between;}
      .foot{margin-top:36px;text-align:center;font-size:10px;color:#64748b;border-top:1px solid #e2e8f0;padding-top:10px;}
      .no-print{display:none !important;}
    </style></head><body>
    <div class="doc-head">
      <h1>${SCHOOL_NAME.toUpperCase()}</h1>
      <p>${SCHOOL_MOTTO} &middot; ${SCHOOL_APPROVAL_NO}</p>
      <p>${SCHOOL_PHONES.join(" , ")}</p>
    </div>
    ${node.innerHTML}
    <div class="foot">This document was generated by the school office. Kindly retain it for your records.</div>
    </body></html>`);
  win.document.close();
  win.focus();
  setTimeout(() => win.print(), 250);
};
