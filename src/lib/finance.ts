import { SCHOOL_NAME, SCHOOL_MOTTO, SCHOOL_APPROVAL_NO, SCHOOL_PHONES } from "@/assets/logo";

/** Naira formatter used everywhere money is shown. */
export const naira = (value: number | string | null | undefined) =>
  `₦${Number(value || 0).toLocaleString("en-NG", { maximumFractionDigits: 2 })}`;

export type InvoiceStatus = "unpaid" | "part_paid" | "paid";

export const invoiceStatusLabel = (status?: string | null) =>
  status === "paid" ? "Paid in full" : status === "part_paid" ? "Part payment" : "Unpaid";

export const invoiceStatusTone = (status?: string | null) =>
  status === "paid"
    ? "bg-success/10 text-success border-success/20"
    : status === "part_paid"
      ? "bg-warning/10 text-warning border-warning/20"
      : "bg-destructive/10 text-destructive border-destructive/20";

export const balanceOf = (invoice: { total?: number | null; amount_paid?: number | null } | null | undefined) =>
  Number(invoice?.total || 0) - Number(invoice?.amount_paid || 0);

export const isOverdue = (invoice: { due_date?: string | null; total?: number | null; amount_paid?: number | null }) =>
  Boolean(invoice.due_date) && balanceOf(invoice) > 0 && new Date(invoice.due_date as string) < new Date();

/** Replaces {{placeholder}} tokens in a message template. */
export const renderTemplate = (body: string, values: Record<string, string>) =>
  body.replace(/\{\{\s*([a-z_]+)\s*\}\}/gi, (_m, key: string) => values[key.toLowerCase()] ?? `{{${key}}}`);

